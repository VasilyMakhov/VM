    NAME VARCHAR(50) NOT NULL,
    CONSTRAINT PK_DELIVERY_STATUSES PRIMARY KEY (ID),
    CONSTRAINT UQ_DELIVERY_STATUSES_NAME UNIQUE (NAME)
);


CREATE TABLE USERS (
    ID         INTEGER NOT NULL,
    LOGIN      VARCHAR(50) NOT NULL,
    EMAIL      VARCHAR(100) NOT NULL,
    PASSWORD   VARCHAR(255) NOT NULL,
    FIRST_NAME VARCHAR(50) NOT NULL,
    LAST_NAME  VARCHAR(50) NOT NULL,
    ROLE_ID    INTEGER NOT NULL,
    CONSTRAINT PK_USERS PRIMARY KEY (ID),
    CONSTRAINT UQ_USERS_LOGIN UNIQUE (LOGIN),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL)
);


CREATE TABLE CATEGORIES (
    ID          INTEGER NOT NULL,
    NAME        VARCHAR(100) NOT NULL,
    DESCRIPTION BLOB SUB_TYPE TEXT,
    CONSTRAINT PK_CATEGORIES PRIMARY KEY (ID),
    CONSTRAINT UQ_CATEGORIES_NAME UNIQUE (NAME)
);

CREATE TABLE WAREHOUSES (
    ID      INTEGER NOT NULL,
    NAME    VARCHAR(100) NOT NULL,
    ADDRESS VARCHAR(255) NOT NULL,
    CONSTRAINT PK_WAREHOUSES PRIMARY KEY (ID)
);


CREATE TABLE PRODUCTS (
    ID          INTEGER NOT NULL,
    CATEGORY_ID INTEGER NOT NULL,
    NAME        VARCHAR(150) NOT NULL,
    DESCRIPTION BLOB SUB_TYPE TEXT,
    IMAGE_URL   VARCHAR(255),
    PRICE       DECIMAL(12, 2),
    CONSTRAINT PK_PRODUCTS PRIMARY KEY (ID)
);

CREATE TABLE SELLER_PRODUCTS (
    ID         INTEGER NOT NULL,
    SELLER_ID  INTEGER NOT NULL,
    PRODUCT_ID INTEGER NOT NULL,
    CONSTRAINT PK_SELLER_PRODUCTS PRIMARY KEY (ID),
    CONSTRAINT UQ_SELLER_PRODUCTS UNIQUE (SELLER_ID, PRODUCT_ID)
);

CREATE TABLE WAREHOUSE_PRODUCTS (
    ID                INTEGER NOT NULL,
    WAREHOUSE_ID      INTEGER NOT NULL,
    SELLER_PRODUCT_ID INTEGER NOT NULL,
    QUANTITY          INTEGER NOT NULL,
    CONSTRAINT PK_WAREHOUSE_PRODUCTS PRIMARY KEY (ID),
    CONSTRAINT UQ_WAREHOUSE_SELLER_PRODUCT UNIQUE (WAREHOUSE_ID, SELLER_PRODUCT_ID),
    CONSTRAINT CHK_WAREHOUSE_QUANTITY CHECK (QUANTITY >= 0)
);


CREATE TABLE FAVORITES (
    ID         INTEGER NOT NULL,
    USER_ID    INTEGER NOT NULL,
    PRODUCT_ID INTEGER NOT NULL,
    CONSTRAINT PK_FAVORITES PRIMARY KEY (ID),
    CONSTRAINT UQ_FAVORITES_USER_PRODUCT UNIQUE (USER_ID, PRODUCT_ID)
);

CREATE TABLE CART_ITEMS (
    ID                INTEGER NOT NULL,
    USER_ID           INTEGER NOT NULL,
    QUANTITY          INTEGER NOT NULL,
    SELLER_PRODUCT_ID INTEGER NOT NULL,
    CONSTRAINT PK_CART_ITEMS PRIMARY KEY (ID),
    CONSTRAINT UQ_CART_USER_PRODUCT UNIQUE (USER_ID, SELLER_PRODUCT_ID),
    CONSTRAINT CHK_CART_QUANTITY CHECK (QUANTITY > 0)
);


CREATE TABLE ORDERS (
    ID                 INTEGER NOT NULL,
    USER_ID            INTEGER NOT NULL,
    TOTAL_PRICE        DECIMAL(10, 2) NOT NULL,
    STATUS_ID          INTEGER NOT NULL,
    DELIVERY_ADDRESS   VARCHAR(255) NOT NULL,
    CREATED_AT         TIMESTAMP NOT NULL,
    PAYMENT_METHOD_ID  INTEGER,
    PAYMENT_STATUS_ID  INTEGER,
    DELIVERY_STATUS_ID INTEGER,
    CONSTRAINT PK_ORDERS PRIMARY KEY (ID),
    CONSTRAINT CHK_ORDERS_TOTAL_PRICE CHECK (TOTAL_PRICE >= 0)
);

CREATE TABLE ORDER_ITEMS (
    ID                INTEGER NOT NULL,
    ORDER_ID          INTEGER NOT NULL,
    QUANTITY          INTEGER NOT NULL,
    PRICE             DECIMAL(10, 2) NOT NULL,
    SELLER_PRODUCT_ID INTEGER NOT NULL,
    CONSTRAINT PK_ORDER_ITEMS PRIMARY KEY (ID),
    CONSTRAINT CHK_ORDER_ITEMS_QUANTITY CHECK (QUANTITY > 0),
    CONSTRAINT CHK_ORDER_ITEMS_PRICE CHECK (PRICE >= 0)
);

CREATE TABLE ORDER_SELLERS (
    ID                  INTEGER NOT NULL,
    ORDER_ID            INTEGER NOT NULL,
    SELLER_ID           INTEGER NOT NULL,
    PAYMENT_CONFIRMED   SMALLINT DEFAULT 0 NOT NULL,
    HANDED_TO_DELIVERY  SMALLINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ORDER_SELLERS PRIMARY KEY (ID),
    CONSTRAINT UQ_ORDER_SELLERS UNIQUE (ORDER_ID, SELLER_ID)
);

