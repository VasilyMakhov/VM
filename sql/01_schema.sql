CREATE TABLE ROLES (
    ID   INTEGER NOT NULL,
    NAME VARCHAR(50) NOT NULL,
    CONSTRAINT PK_ROLES PRIMARY KEY (ID),
    CONSTRAINT UQ_ROLES_NAME UNIQUE (NAME)
);

CREATE TABLE ORDER_STATUSES (
    ID   INTEGER NOT NULL,
